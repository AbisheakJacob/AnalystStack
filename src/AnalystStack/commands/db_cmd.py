"""``analyststack db``: read-only database access with every statement saved to the task.

Rules that every subcommand follows:

* Connections are referred to by *name*; credentials come from the ``.env`` cascade and are
  never shown.
* User SQL must pass `AnalystStack.sql_guard.assert_read_only` for the connection's dialect
  before anything is saved or sent.
* Every statement that is executed is saved to ``<task>/sql/NN_slug.sql`` with an
  Author/Date/Title/Description header and recorded in ``sql/_runs.jsonl``. ``db query`` uses
  the title and description you give; ``tables``, ``columns``, ``profile`` and ``freshness``
  save the statements they ran with an auto-generated title and description.
* With no active task and no ``--task-dir``, a command refuses to run. ``--scratch`` saves to
  ``_state/inbox/sql/`` instead.
* There is no command that writes to a database.
"""

import argparse
import sys
import time
from pathlib import Path

from AnalystStack.commands._common import EXIT_FAIL, default_scope, guarded, show_frame, write_frame
from AnalystStack.connections import OpenConnection, list_connections, load_registry, open_connection
from AnalystStack.connectors.freshness import DEFAULT_COLUMN, check_freshness
from AnalystStack.connectors.readonly import capture_sql
from AnalystStack.exceptions.errors import ConfigurationError, PathPolicyError, ValidationError
from AnalystStack.paths import check_read, check_write
from AnalystStack.sql_guard import DIALECT_BY_TYPE, assert_read_only
from AnalystStack.sqllog import read_author, record_run, save_query
from AnalystStack.utils.validation import validate_identifier
from AnalystStack.workspace import active_task_dir, find_workspace_root

DEFAULT_ROW_LIMIT = 100_000
AUTO_NOTE = "auto-generated by analyststack"


def _scope(args: argparse.Namespace) -> Path:
    return Path(args.scope).resolve() if getattr(args, "scope", None) else default_scope()


def _task_dir(args: argparse.Namespace) -> Path:
    """Decides where SQL is saved, failing closed when nothing is active."""
    root = find_workspace_root()
    if args.task_dir:
        task = Path(args.task_dir).resolve()
    elif root is not None and (active := active_task_dir(root)) is not None:
        task = active
    elif args.scratch and root is not None:
        task = root / "_state" / "inbox"
    else:
        raise PathPolicyError(
            "No active task. Run `python scripts/task.py switch ...`, pass --task-dir, or use --scratch."
        )
    check_write(task / "sql" / "probe.sql")  # applies the active-task and protected-folder rules
    return task


def _author(args: argparse.Namespace) -> str:
    if args.author:
        return str(args.author)
    root = find_workspace_root()
    if root is None:
        raise ConfigurationError("Pass --author when running outside a workspace.")
    return read_author(root)


def _dialect_for(args: argparse.Namespace) -> str:
    registry = load_registry(_scope(args))
    if args.connection not in registry:
        raise ConfigurationError(f"Unknown connection {args.connection!r}. Known: {sorted(registry) or 'none'}.")
    return DIALECT_BY_TYPE[registry[args.connection]["type"]]


def _save_and_run(
    conn: OpenConnection, sql: str, title: str, description: str, args: argparse.Namespace, limit: int | None
):
    """Guards, saves, runs and records one user statement. Returns the DataFrame."""
    tree = assert_read_only(sql, conn.dialect)
    task = _task_dir(args)
    saved = save_query(task, sql, title, description, author=_author(args))
    executed, note = sql, None
    if limit is not None:
        try:
            existing = tree.args.get("limit")
            current = int(getattr(existing.expression, "name", "")) if existing is not None else None
        except (AttributeError, ValueError):
            current = None
        if current is None or current > limit:
            executed = tree.limit(limit).sql(dialect=conn.dialect)
            note = f"row cap {limit} applied"
    started = time.monotonic()
    try:
        frame = conn.connector.read_data(executed)
    except Exception:
        record_run(
            task, saved, connection=conn.name, rows=None, ok=False, seconds=time.monotonic() - started, note=note
        )
        raise
    record_run(
        task, saved, connection=conn.name, rows=len(frame), ok=True, seconds=time.monotonic() - started, note=note
    )
    print(f"saved: {saved.path}{' (identical statement, existing file kept)' if saved.reused else ''}")
    if note:
        print(note)
    return frame


def _save_captured(
    conn: OpenConnection, statements: list[str], title: str, description: str, args, rows: int | None
) -> None:
    task = _task_dir(args)
    author = _author(args)
    for index, statement in enumerate(statements, start=1):
        suffix = f" (statement {index} of {len(statements)})" if len(statements) > 1 else ""
        saved = save_query(task, statement, title + suffix, f"{description} ({AUTO_NOTE}).", author=author)
        record_run(task, saved, connection=conn.name, rows=rows, ok=True, note=AUTO_NOTE)
        print(f"saved: {saved.path}")


def _read_sql(args: argparse.Namespace) -> str:
    if bool(args.sql) == bool(args.file):
        raise ValidationError("Give exactly one of --sql or --file.")
    return args.sql if args.sql else check_read(args.file).read_text(encoding="utf-8")


@guarded
def handle_connections(args: argparse.Namespace) -> None:
    """Lists connection names, types and the *names* of the variables they need."""
    rows = list_connections(_scope(args))
    if not rows:
        print("No connections defined in config.yaml at any level.")
    for row in rows:
        print(f"{row['name']}\t{row['type']}\tvars: {', '.join(row['env_vars']) or '-'}")


@guarded
def handle_check_sql(args: argparse.Namespace) -> None:
    """Runs only the read-only guard (no connection) and prints OK or the refusal reason."""
    sql = _read_sql(args)
    assert_read_only(sql, args.dialect)
    print("OK: single read-only statement.")


@guarded
def handle_query(args: argparse.Namespace) -> None:
    """Runs one guarded, saved, row-capped read."""
    sql = _read_sql(args)
    out_path = check_write(args.out) if args.out else None  # refuse a bad output path before running
    assert_read_only(sql, _dialect_for(args))
    conn = open_connection(args.connection, _scope(args))
    print(f"connection: {conn.name} ({conn.type}); {conn.note}")
    limit = None if args.no_limit else args.limit
    frame = _save_and_run(conn, sql, args.title, args.description, args, limit)
    show_frame(frame)
    if out_path is not None:
        print(f"wrote: {write_frame(frame, str(out_path))}")


@guarded
def handle_tables(args: argparse.Namespace) -> None:
    """Lists base tables in a schema and saves the catalog SQL that was run."""
    validate_identifier(args.schema, "schema")
    conn = open_connection(args.connection, _scope(args))
    with capture_sql(conn.connector) as statements:
        frame = conn.connector.list_tables(args.schema)
    show_frame(frame, rows=200)
    _save_captured(
        conn,
        statements,
        f"Catalog: tables in {args.schema}",
        f"Lists base tables in schema {args.schema}",
        args,
        len(frame),
    )


@guarded
def handle_columns(args: argparse.Namespace) -> None:
    """Lists the columns of a table and saves the catalog SQL that was run."""
    validate_identifier(args.schema, "schema")
    validate_identifier(args.table, "table")
    conn = open_connection(args.connection, _scope(args))
    with capture_sql(conn.connector) as statements:
        frame = conn.connector.list_columns(args.schema, args.table)
    show_frame(frame, rows=200)
    title = f"Catalog: columns of {args.schema}.{args.table}"
    _save_captured(conn, statements, title, f"Lists the columns of {args.schema}.{args.table}", args, len(frame))


@guarded
def handle_profile(args: argparse.Namespace) -> None:
    """Profiles a table's columns and saves the SQL that was run."""
    validate_identifier(args.schema, "schema")
    validate_identifier(args.table, "table")
    conn = open_connection(args.connection, _scope(args))
    with capture_sql(conn.connector) as statements:
        frame = conn.connector.profile_columns(args.schema, args.table)
    show_frame(frame, rows=200)
    title = f"Profile: {args.schema}.{args.table}"
    _save_captured(
        conn,
        statements,
        title,
        f"Per-column profile (fill rate and distinct counts) of {args.schema}.{args.table}",
        args,
        len(frame),
    )


@guarded
def handle_freshness(args: argparse.Namespace) -> None:
    """Checks the newest value of a timestamp column and exits 1 if it is too old."""
    conn = open_connection(args.connection, _scope(args))
    result = check_freshness(conn.connector, args.table, args.column)
    _save_captured(
        conn,
        [result.sql],
        f"Freshness: {args.table}",
        f"Newest {args.column} in {args.table}, to measure how stale the data is",
        args,
        1,
    )
    print(f"table={result.table} column={result.column} max={result.max_value} age_hours={result.age_hours}")
    if args.max_age_hours is not None:
        if result.is_fresh(args.max_age_hours):
            print(f"FRESH: within {args.max_age_hours} hours.")
        else:
            print(f"STALE: older than {args.max_age_hours} hours (or empty).")
            sys.exit(EXIT_FAIL)


def _common(parser: argparse.ArgumentParser, *, connection: bool = True) -> None:
    if connection:
        parser.add_argument("--connection", required=True, help="Connection name from config.yaml.")
    parser.add_argument(
        "--scope", default=None, help="Folder deciding which config and env levels apply (default: active task or cwd)."
    )
    parser.add_argument("--task-dir", default=None, help="Save SQL under this task instead of the active task.")
    parser.add_argument("--scratch", action="store_true", help="With no active task, save SQL to _state/inbox/sql/.")
    parser.add_argument("--author", default=None, help="Header author (default: `author` in global/config.yaml).")


def add_parser(subparsers) -> None:
    """Registers ``db`` and its subcommands."""
    db = subparsers.add_parser("db", help="Read-only database access; every statement is saved to the task.")
    sub = db.add_subparsers(dest="db_command", required=True)

    conns = sub.add_parser("connections", help="List connection names (no secrets).")
    conns.add_argument("--scope", default=None)
    conns.set_defaults(func=handle_connections)

    check = sub.add_parser("check-sql", help="Run only the read-only guard; no connection is made.")
    check.add_argument("--sql", default=None)
    check.add_argument("--file", default=None)
    check.add_argument("--dialect", default=None, help="sqlglot dialect, e.g. postgres, bigquery, clickhouse.")
    check.set_defaults(func=handle_check_sql)

    query = sub.add_parser(
        "query", help="Run one read-only query; saves it to the task with your title and description."
    )
    _common(query)
    query.add_argument("--sql", default=None, help="The SQL text.")
    query.add_argument("--file", default=None, help="A file holding the SQL.")
    query.add_argument("--title", required=True, help="One-line title for the saved header.")
    query.add_argument("--description", required=True, help="What the query does and why (saved in the header).")
    query.add_argument("--limit", type=int, default=DEFAULT_ROW_LIMIT, help=f"Row cap (default {DEFAULT_ROW_LIMIT}).")
    query.add_argument("--no-limit", action="store_true", help="Do not add a row cap.")
    query.add_argument("--out", default=None, help="Write the full result to .csv, .xlsx, .parquet, .md or .txt.")
    query.set_defaults(func=handle_query)

    tables = sub.add_parser("tables", help="List base tables in a schema.")
    _common(tables)
    tables.add_argument("--schema", required=True)
    tables.set_defaults(func=handle_tables)

    columns = sub.add_parser("columns", help="List a table's columns.")
    _common(columns)
    columns.add_argument("--schema", required=True)
    columns.add_argument("--table", required=True)
    columns.set_defaults(func=handle_columns)

    profile = sub.add_parser("profile", help="Profile a table's columns.")
    _common(profile)
    profile.add_argument("--schema", required=True)
    profile.add_argument("--table", required=True)
    profile.set_defaults(func=handle_profile)

    fresh = sub.add_parser("freshness", help="Check how old the newest value of a timestamp column is.")
    _common(fresh)
    fresh.add_argument("--table", required=True, help="schema.table")
    fresh.add_argument("--column", default=DEFAULT_COLUMN, help=f"Timestamp column (default {DEFAULT_COLUMN}).")
    fresh.add_argument("--max-age-hours", type=float, default=None, help="Exit 1 if older than this.")
    fresh.set_defaults(func=handle_freshness)
